export const getSettingText = (text) => settingsText[text] || text;

export const getRoleLabel = (role) =>
  role === "professor" ? "Professor" : "Aluno";

export const getStudentTypeLabel = (studentType) =>
  studentType === "kids" ? "Kids" : "Normal";

export const getUserDisplayName = (user = {}) =>
  user.username || user.displayName || user.name || "Usuário";

export const getUserInitials = (user = {}) => {
  const source = getUserDisplayName(user).trim();
  if (!source) return "U";
  const parts = source.split(/\s+/).filter(Boolean);
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return `${parts[0][0] || ""}${
    parts[parts.length - 1][0] || ""
  }`.toUpperCase();
};

export const formatRecentUsage = (lastUsed) => {
  if (lastUsed < 0) return "Adicionado recentemente";
  if (lastUsed < 10) return "Agora mesmo";
  if (lastUsed < 60) return `${lastUsed} min atrás`;
  return `${Math.floor(lastUsed / 60)} h atrás`;
};
